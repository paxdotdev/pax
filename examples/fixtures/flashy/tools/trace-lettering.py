"""Regenerate the fixture's vector lettering. Requires fonttools and skia-pathops."""
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.varLib.instancer import instantiateVariableFont

FIXTURE = Path(__file__).resolve().parents[1]
ROOT = FIXTURE.parents[2]
font = TTFont(ROOT / "pax-website/assets/fonts/Manrope.ttf")
font = instantiateVariableFont(font, {"wght": 800}, inplace=True)
# Font fills can contain overlapping contours; strokes need their actual union.
removeOverlaps(font)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
commands = []
offset = 0


class Pen(BasePen):
    def _moveTo(self, p):
        commands.append(("M", offset + p[0], -p[1]))

    def _lineTo(self, p):
        commands.append(("L", offset + p[0], -p[1]))

    def _qCurveToOne(self, c, p):
        commands.append(("Q", offset + c[0], -c[1], offset + p[0], -p[1]))

    def _curveToOne(self, a, b, p):
        commands.append(("C", offset + a[0], -a[1], offset + b[0], -b[1], offset + p[0], -p[1]))

    def _closePath(self):
        commands.append(("Z",))


for char in "flashy":
    glyph = glyphs[cmap[ord(char)]]
    glyph.draw(Pen(glyphs))
    offset += glyph.width

xs = [c[i] for c in commands for i in range(1, len(c), 2)]
ys = [c[i] for c in commands for i in range(2, len(c), 2)]
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)


def point(x, y):
    return f"s({(x - x0) / (x1 - x0) * 100:.6f}), s({(y - y0) / (y1 - y0) * 100:.6f})"


lines = [
    "// Generated by tools/trace-lettering.py from Manrope ExtraBold (OFL).",
    "// Normalized unioned outlines; no font parser runs in the app.",
    "use pax_kit::*;", "", "pub fn lettering() -> Vec<PathElement> {",
    "    let s = |v: f64| Size::Percent(v.into());", "    vec![",
]
for kind, *args in commands:
    if kind == "Z":
        lines.append("        PathElement::Close,")
        continue
    if kind == "L":
        lines.append("        PathElement::Line,")
    elif kind == "Q":
        lines.append(f"        PathElement::Quadratic({point(*args[:2])}),")
    elif kind == "C":
        lines.append(f"        PathElement::Cubic({point(*args[:2])}, {point(*args[2:4])}),")
    lines.append(f"        PathElement::Point({point(*args[-2:])}),")
lines.extend(["    ]", "}"])
(FIXTURE / "src/lettering.rs").write_text("\n".join(lines) + "\n")
