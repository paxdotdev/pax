//! Selects the UI library independently of the package owning the process entry.
use cargo_metadata::MetadataCommand;
use color_eyre::eyre::{eyre, Result};
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};

/// A library-specific wasm export keeps runnable dependencies linkable together.
/// Packaging aliases the selected library's export to the public `init_web`.
pub fn web_entrypoint(package_id: &str, library_name: &str) -> String {
    let identity = serde_json::to_vec(&(package_id, library_name)).unwrap();
    format!("__pax_init_web_{:x}", Sha256::digest(identity))
}

/// Program-owned C exports for one Cargo library. Keep this identity separate
/// from the content-based program ID: within one Cargo library identity, source
/// edits and target architectures must not change a universal framework's names.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NativeExports {
    pub abi_version: String,
    pub program_id: String,
    pub init: String,
    pub init_with_data: String,
    pub init_entry: String,
}

impl NativeExports {
    /// Derive linker names from Cargo's full package ID and library target,
    /// independently of dependency aliases and the current program contents.
    pub fn new(package_id: &str, library_name: &str) -> Self {
        let identity =
            serde_json::to_vec(&("pax-native-exports-v1", package_id, library_name)).unwrap();
        let suffix = format!("{:x}", Sha256::digest(identity));
        let symbol = |name: &str| format!("{name}_{suffix}");
        Self {
            abi_version: symbol("pax_cartridge_abi_version"),
            program_id: symbol("pax_cartridge_program_id"),
            init: symbol("pax_init"),
            init_with_data: symbol("pax_init_with_data"),
            init_entry: symbol("pax_init_entry"),
        }
    }

    /// Bind ordinary C/Swift declaration names to the selected program without
    /// emitting generic aliases into any application or dependency library.
    pub fn apple_header(&self) -> String {
        let mut header = String::from("// Generated by Pax for the selected UI library.\n#pragma once\n#define PAX_PROGRAM_EXPORT(name) PAX_PROGRAM_EXPORT_ ## name\n");
        for (name, symbol) in [
            ("pax_cartridge_abi_version", &self.abi_version),
            ("pax_cartridge_program_id", &self.program_id),
            ("pax_init", &self.init),
            ("pax_init_with_data", &self.init_with_data),
            ("pax_init_entry", &self.init_entry),
        ] {
            // Mach-O assembler labels include the C underscore prefix.
            header.push_str(&format!(
                "#define PAX_PROGRAM_EXPORT_{name} __asm__(\"_{symbol}\")\n"
            ));
        }
        header
    }
}

/// Cargo paths used for a Pax build. Generated files and host metadata remain
/// under the requested application package, even when its UI is a sibling.
#[derive(Clone, Debug)]
pub struct ProjectLayout {
    pub cartridge_dir: PathBuf,
    pub target_dir: PathBuf,
    pub library_name: String,
    pub web_entrypoint: String,
    pub native_exports: NativeExports,
    pub exports_cartridge: bool,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn web_exports_distinguish_package_and_library_identity() {
        let export = web_entrypoint("path+file:///app", "ui");
        assert_eq!(export, web_entrypoint("path+file:///app", "ui"));
        assert_ne!(export, web_entrypoint("path+file:///dependency", "ui"));
        assert_ne!(export, web_entrypoint("path+file:///app", "another_ui"));
        assert!(export
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_'));
    }

    #[test]
    fn native_exports_distinguish_versions_sources_and_library_targets() {
        let id = "registry+https://example.test/index#ui@1.0.0";
        let exports = NativeExports::new(id, "ui");
        assert_eq!(exports, NativeExports::new(id, "ui"));
        for (package, library) in [
            ("registry+https://example.test/index#ui@2.0.0", "ui"),
            ("registry+https://other.test/index#ui@1.0.0", "ui"),
            (id, "another_ui"),
        ] {
            assert_ne!(exports, NativeExports::new(package, library));
        }
        let metadata = serde_json::to_value(&exports).unwrap();
        assert_eq!(metadata["initEntry"], exports.init_entry);
        let names = metadata
            .as_object()
            .unwrap()
            .values()
            .map(|v| v.as_str().unwrap())
            .collect::<std::collections::HashSet<_>>();
        assert_eq!(names.len(), 5);
        assert!(names
            .iter()
            .all(|name| name.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_')));
        let header = exports.apple_header();
        for name in names {
            assert!(header.contains(&format!("__asm__(\"_{name}\")")));
        }
    }

    #[test]
    fn rejects_unknown_workspace_packages_and_mismatched_library_targets() {
        let root = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(root.path().join("host/src")).unwrap();
        std::fs::create_dir_all(root.path().join("ui/src")).unwrap();
        std::fs::write(
            root.path().join("Cargo.toml"),
            "[workspace]\nmembers=['host','ui']\nresolver='2'\n",
        )
        .unwrap();
        std::fs::write(root.path().join("host/src/main.rs"), "fn main() {}\n").unwrap();
        std::fs::write(root.path().join("ui/src/lib.rs"), "").unwrap();
        std::fs::write(root.path().join("ui/Cargo.toml"), "[package]\nname='layout-ui'\nversion='0.1.0'\n[lib]\nname='chosen_ui'\ncrate-type=['rlib','cdylib']\n").unwrap();
        for (selection, error) in [
            ("package='missing'", "not a member"),
            ("package='layout-ui'\nlib='wrong'", "does not match"),
            ("package='layout-ui'\nlibs='chosen_ui'", "Unknown"),
            ("package=12", "must name"),
        ] {
            std::fs::write(root.path().join("host/Cargo.toml"), format!("[package]\nname='layout-host'\nversion='0.1.0'\n[package.metadata.pax.cartridge]\n{selection}\n")).unwrap();
            assert!(ProjectLayout::resolve(&root.path().join("host"))
                .unwrap_err()
                .to_string()
                .contains(error));
        }
    }
}

impl ProjectLayout {
    pub fn resolve(project_dir: &Path) -> Result<Self> {
        let manifest = project_dir.join("Cargo.toml").canonicalize()?;
        let metadata = MetadataCommand::new()
            .manifest_path(&manifest)
            .no_deps()
            .exec()?;
        let host = metadata
            .packages
            .iter()
            .find(|package| {
                package
                    .manifest_path
                    .as_std_path()
                    .canonicalize()
                    .ok()
                    .as_deref()
                    == Some(manifest.as_path())
            })
            .ok_or_else(|| {
                eyre!(
                    "Select an application package, rather than a virtual workspace: {}",
                    manifest.display()
                )
            })?;
        let selection = host
            .metadata
            .get("pax")
            .and_then(|pax| pax.get("cartridge"));
        let cartridge = if let Some(selection) = selection {
            let fields = selection.as_object().ok_or_else(|| eyre!("package.metadata.pax.cartridge must be a table with `package` and optional `lib`"))?;
            if let Some(unknown) = fields
                .keys()
                .find(|key| !matches!(key.as_str(), "package" | "lib"))
            {
                return Err(eyre!("Unknown package.metadata.pax.cartridge key `{unknown}`; expected `package` or `lib`"));
            }
            let name = selection
                .get("package")
                .and_then(|value| value.as_str())
                .ok_or_else(|| {
                    eyre!("package.metadata.pax.cartridge.package must name a workspace package")
                })?;
            metadata.packages.iter().find(|package| package.name == name && metadata.workspace_members.contains(&package.id))
                .ok_or_else(|| eyre!("Selected cartridge package `{name}` is not a member of this Cargo workspace"))?
        } else {
            host
        };
        let library = cartridge.targets.iter().find(|target| target.kind.iter().any(|kind| matches!(kind.as_str(), "lib" | "rlib" | "cdylib" | "dylib" | "staticlib")))
            .ok_or_else(|| eyre!("Cartridge package `{}` needs a library with crate-type = [\"rlib\", \"cdylib\"]", cartridge.name))?;
        if let Some(value) = selection.and_then(|selection| selection.get("lib")) {
            let name = value.as_str().ok_or_else(|| {
                eyre!("package.metadata.pax.cartridge.lib must be a library target name")
            })?;
            if name != library.name {
                return Err(eyre!(
                    "Selected library `{name}` does not match `{}` in cartridge package `{}`",
                    library.name,
                    cartridge.name
                ));
            }
        }
        Ok(Self {
            cartridge_dir: cartridge
                .manifest_path
                .parent()
                .unwrap()
                .as_std_path()
                .canonicalize()?,
            target_dir: metadata.target_directory.into_std_path_buf(),
            library_name: library.name.clone(),
            web_entrypoint: web_entrypoint(&cartridge.id.repr, &library.name),
            native_exports: NativeExports::new(&cartridge.id.repr, &library.name),
            exports_cartridge: library.crate_types.iter().any(|kind| kind == "cdylib"),
        })
    }

    pub fn configure_cartridge(&self, command: &mut std::process::Command) {
        command
            .env("PAX_CARTRIDGE_MANIFEST_DIR", &self.cartridge_dir)
            .env("PAX_BUILD_CARTRIDGE", "true");
    }
}
