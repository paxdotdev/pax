//! Explicit, website-specific extraction; ordinary website builds never run this.
mod font;
use font::{OutlineCommand, OutlineFont};
use sha2::{Digest, Sha256};
use std::{error::Error, fmt::Write, fs, path::Path};

const WORDS: [&str; 3] = ["high-performance", "native", "portable"];
const WEIGHT: f32 = 800.0;
const ACROSTIC_ALPHABET: &str = "ACDEFKLMNOPRY";

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = match args.as_slice() {
        [] => false,
        [arg] if arg == "--check" => true,
        _ => return Err("usage: trace-hero [--check]".into()),
    };
    let website = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let bytes = fs::read(website.join("assets/fonts/Manrope.ttf"))?;
    let checksum = format!("{:x}", Sha256::digest(&bytes));
    let mut font = OutlineFont::new(bytes, WEIGHT)?;
    let mut outlines: Vec<Vec<OutlineCommand>> = Vec::new();
    let mut output = format!(
        "// Generated by tools/trace-hero; regenerate with the command in README.md.\n\
         // Manrope.ttf SHA-256: {checksum}; wght={WEIGHT}; HarfRust 0.14.0 / Skrifa 0.48.0.\n\
         // Exact unhinted Bézier outlines in em units, y down, baseline y=0.\n\
         // Layout follows whole-phrase shaping; contours are shared where identical.\n\n\
         #[rustfmt::skip]\nconst RUNS: &[BakedRun; 3] = &[\n"
    );
    for word in WORDS {
        let run = font.shape_line(word)?;
        let baseline = (1.5 - (run.ascent - run.descent)) / 2.0 + run.ascent;
        writeln!(output, "    BakedRun {{ text: {word:?}, advance: {:?}, baseline: {baseline:?}, cap_height: {:?}, clusters: &[", run.advance, run.cap_height)?;
        for cluster in run.clusters {
            let outline = outlines
                .iter()
                .position(|x| x == &cluster.outline)
                .unwrap_or_else(|| {
                    outlines.push(cluster.outline);
                    outlines.len() - 1
                });
            writeln!(output, "        BakedCluster {{ byte_start: {}, byte_end: {}, x: {:?}, advance: {:?}, glyph_ids: &{:?}, outline: {outline} }},", cluster.byte_start, cluster.byte_end, cluster.x, cluster.advance, cluster.glyph_ids)?;
        }
        output.push_str("    ] },\n");
    }
    output.push_str("];\n\n#[rustfmt::skip]\nconst OUTLINES: &[&[Command]] = &[\n");
    for outline in &outlines {
        output.push_str("    &[\n");
        for command in outline {
            writeln!(output, "        Command::{command:?},")?;
        }
        output.push_str("    ],\n");
    }
    output.push_str("];\n");
    let destination = website.join("src/hero_outlines_data.rs");
    if check {
        if fs::read_to_string(&destination)? != output {
            return Err(
                "Hero outlines are stale; run trace-hero without --check and review the diff."
                    .into(),
            );
        }
        println!(
            "Hero outlines match the font and shaping helper ({} unique outlines).",
            outlines.len()
        );
    } else {
        fs::write(&destination, output)?;
        println!(
            "Wrote {} ({} unique outlines).",
            destination.display(),
            outlines.len()
        );
    }
    let mut output = format!(
        "// Generated by tools/trace-hero; regenerate with the command in README.md.\n\
         // Manrope.ttf SHA-256: {checksum}; wght={WEIGHT}; HarfRust 0.14.0 / Skrifa 0.48.0.\n\
         // Isolated uppercase letters for the fixed acrostic cell grid; em units, baseline y=0.\n\n\
         #[rustfmt::skip]\nconst ACROSTIC_GLYPHS: &[BakedGlyph] = &[\n"
    );
    for letter in ACROSTIC_ALPHABET.chars() {
        let run = font.shape_line(&letter.to_string())?;
        assert_eq!(run.clusters.len(), 1);
        writeln!(output, "    BakedGlyph {{ letter: {letter:?}, commands: &[")?;
        for command in &run.clusters[0].outline {
            writeln!(output, "        Command::{command:?},")?;
        }
        output.push_str("    ] },\n");
    }
    output.push_str("];\n");
    let destination = website.join("src/acrostic_outlines_data.rs");
    if check {
        if fs::read_to_string(&destination)? != output {
            return Err("Acrostic outlines are stale; run trace-hero without --check.".into());
        }
        println!("Acrostic outlines match the font and shaping helper.");
    } else {
        fs::write(&destination, output)?;
        println!("Wrote {}.", destination.display());
    }
    Ok(())
}
